import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  page.on('pageerror', error => { throw error })
  await page.route(url => !['127.0.0.1', 'localhost'].includes(url.hostname), route => route.abort())
  // All application API requests are synthetic and stay off production services.
  await page.route('**/api/**', route => route.fulfill({ json: {} }))
  await page.route('**/api/account', route => route.fulfill({ json: { username: 'SyntheticStudent', email: 'synthetic@example.test' } }))
})

test('public direct routes, refresh, footer navigation and hash destinations', async ({ page }) => {
  for (const [route, title] of [['/about', 'About LearnMatch'], ['/help', 'Help Center'], ['/terms', 'Terms & Conditions'], ['/privacy', 'LearnMatch Privacy Notice']]) {
    const response = await page.goto(route)
    expect(response.status()).toBe(200)
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
    expect(await page.evaluate(() => localStorage.getItem('token'))).toBeNull()
  }
  await page.goto('/')
  const footer = page.getByRole('contentinfo')
  for (const [name, path] of [['About LearnMatch', '/about'], ['Help Center', '/help'], ['Terms & Conditions', '/terms'], ['Privacy Notice', '/privacy']]) {
    await footer.getByRole('link', { name, exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`${path}$`))
  }
  await footer.getByRole('link', { name: 'Contact Support', exact: true }).click()
  await expect(page.locator('#contact-support')).toBeInViewport()
  await expect(page.locator('#contact-support').getByRole('link', { name: 'learnmatch1@gmail.com' })).toHaveAttribute('href', 'mailto:learnmatch1@gmail.com')
  await footer.getByRole('link', { name: 'How It Works', exact: true }).click()
  await expect(page.locator('#how-it-works')).toBeInViewport()
})

test('required agreement blocks requests; related documents preserve form, checkbox and keyboard focus', async ({ page }) => {
  await page.clock.install()
  let requests = 0
  await page.route('**/api/auth/register', async route => {
    requests++
    const body = route.request().postDataJSON()
    expect(body.agreementAccepted).toBe(true)
    expect(body.termsVersion).toBe('1.0')
    expect(body.privacyNoticeVersion).toBe('1.3')
    await route.fulfill({ status: 201, json: { userId: 12 } })
  })
  await page.route('**/api/auth/verify-otp', route => route.fulfill({ status: 400, json: { message: 'Synthetic invalid code' } }))
  await page.route('**/api/auth/resend-otp', route => route.fulfill({ json: { message: 'Synthetic code resent' } }))
  await page.goto('/register')
  await page.locator('[name="email"]').fill('synthetic@example.test')
  await page.locator('[name="username"]').fill('synthetic_student')
  await page.locator('[name="password"]').fill('Password1')
  await page.locator('[name="confirmPassword"]').fill('Password1')
  const checkbox = page.getByRole('checkbox')
  await expect(checkbox).not.toBeChecked()
  await page.getByRole('button', { name: 'Register', exact: true }).click()
  await expect(checkbox).toBeFocused()
  await expect(page.locator('#registration-agreement-error')).toBeVisible()
  expect(requests).toBe(0)
  await checkbox.press('Space')
  const termsLink = page.getByRole('link', { name: 'Terms & Conditions', exact: true })
  await termsLink.focus()
  await termsLink.press('Enter')
  await expect(page.getByRole('heading', { name: 'Terms & Conditions', exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Public information' }).getByRole('link', { name: 'Privacy Notice', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'LearnMatch Privacy Notice' })).toBeVisible()
  await page.getByRole('button', { name: 'Back to registration' }).click()
  await expect(termsLink).toBeFocused()
  for (const [name, value] of [['email', 'synthetic@example.test'], ['username', 'synthetic_student'], ['password', 'Password1'], ['confirmPassword', 'Password1']]) await expect(page.locator(`[name="${name}"]`)).toHaveValue(value)
  await expect(checkbox).toBeChecked()
  await page.getByRole('link', { name: 'Privacy Notice', exact: true }).first().click()
  await page.getByRole('button', { name: 'Back to registration' }).click()
  await expect(checkbox).toBeChecked()
  await page.getByRole('button', { name: 'Register', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Check your email' })).toBeVisible()
  expect(requests).toBe(1)
  await expect(page.getByRole('button', { name: /Resend Code in/ })).toBeDisabled()
  await page.clock.fastForward(60000)
  await page.getByRole('button', { name: 'Resend Code', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Synthetic code resent')
  await page.getByPlaceholder('000000').fill('000000')
  await expect(page.getByPlaceholder('000000')).toHaveValue('000000')
  await page.getByRole('button', { name: 'Verify Account' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('#register-otp-error')).toHaveText('Synthetic invalid code')
})

test('verified registration shows success before automatically opening the dashboard', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install()
  await page.route('**/api/auth/register', route => route.fulfill({ status: 201, json: { userId: 12 } }))
  await page.route('**/api/auth/verify-otp', route => route.fulfill({ json: { token: 'synthetic-verified-session', userId: 12, username: 'synthetic_student' } }))
  await page.goto('/register')
  for (const [name, value] of [['email', 'synthetic@example.test'], ['username', 'synthetic_student'], ['password', 'Password1'], ['confirmPassword', 'Password1']]) await page.locator(`[name="${name}"]`).fill(value)
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Register', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Check your email' })).toBeVisible()
  await page.getByPlaceholder('000000').fill('123456')
  await page.getByRole('button', { name: 'Verify Account' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Account successfully created!')
  await expect(page).toHaveURL(/\/register$/)
  expect(await page.evaluate(() => localStorage.getItem('token'))).toBeNull()
  await page.clock.fastForward(1200)
  await expect(page).toHaveURL(/\/dashboard$/)
  expect(await page.evaluate(() => localStorage.getItem('token'))).toBe('synthetic-verified-session')
})

test('Help accordions work by keyboard and Settings keeps document return navigation', async ({ page }) => {
  await page.goto('/help')
  const summary = page.locator('summary').first()
  await summary.focus()
  await summary.press('Enter')
  await expect(page.locator('details').first()).toHaveAttribute('open', '')
  await summary.press('Space')
  await expect(page.locator('details').first()).not.toHaveAttribute('open', '')
  await page.evaluate(() => localStorage.setItem('token', 'synthetic-local-session'))
  await page.goto('/settings')
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Terms & Conditions', exact: true }).click()
  await page.getByRole('button', { name: 'Back to Settings' }).click()
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Terms & Conditions', exact: true })).toBeFocused()
  await expect(page.getByRole('button', { name: 'Delete Account', exact: true })).toBeVisible()
})

for (const width of [360, 768, 1440]) test(`public layout fits ${width}px and screenshots`, async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width, height: 900 })
  for (const path of ['/', '/about', '/help', '/terms', '/privacy', '/register']) {
    await page.goto(path)
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const overflowing = await page.locator('main, footer, summary, h1').evaluateAll(elements => elements.filter(el => el.scrollWidth > el.clientWidth + 1).map(el => el.tagName))
    expect(overflowing).toEqual([])
    if (path === '/') {
      await page.getByRole('contentinfo').scrollIntoViewIfNeeded()
      await page.screenshot({ path: testInfo.outputPath(`footer-${width}.png`) })
    }
    if (path === '/help') await page.screenshot({ path: testInfo.outputPath(`help-${width}.png`) })
    if (path === '/register') await page.screenshot({ path: testInfo.outputPath(`register-${width}.png`), fullPage: true })
  }
})

for (const width of [375, 1280]) {
  test(`registration waits 60 seconds before resending and restarts the countdown at ${width}px`, async ({ page }, testInfo) => {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.clock.install()
    await page.setViewportSize({ width, height: 900 })
    let resends = 0
    await page.route('**/api/auth/register', route => route.fulfill({ status: 201, json: { userId: 12 } }))
    await page.route('**/api/auth/resend-otp', route => {
      resends++
      expect(route.request().postDataJSON()).toEqual({ userId: 12, email: 'synthetic@example.test' })
      return route.fulfill({ json: { message: 'If the account is eligible, a new code has been sent.' } })
    })
    await page.route('**/api/auth/verify-otp', route => route.fulfill({ status: 400, json: { message: 'Synthetic invalid code' } }))
    await page.goto('/register')
    for (const [name, value] of [['email', 'synthetic@example.test'], ['username', 'synthetic_student'], ['password', 'Password1'], ['confirmPassword', 'Password1']]) await page.locator(`[name="${name}"]`).fill(value)
    await page.getByRole('checkbox').check()
    // Filling the form slowly must not extend the initial 60-second cooldown.
    await page.clock.fastForward(120000)
    await page.getByRole('button', { name: 'Register', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Resend Code in 60s', exact: true })).toBeDisabled()
    await page.clock.fastForward(30000)
    await expect(page.getByRole('button', { name: 'Resend Code in 30s', exact: true })).toBeDisabled()
    expect(resends).toBe(0)
    await page.clock.fastForward(30000)
    await page.getByPlaceholder('000000').fill('111111')
    await page.getByRole('button', { name: 'Resend Code', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Resend Code in 60s', exact: true })).toBeDisabled()
    await expect(page.getByPlaceholder('000000')).toHaveValue('')
    expect(resends).toBe(1)
    await page.getByPlaceholder('000000').fill('123456')
    await page.getByRole('button', { name: 'Verify Account', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('#register-otp-error')).toHaveText('Synthetic invalid code')
    await expect(page.getByRole('button', { name: /Resend Code in/ })).toBeDisabled()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`registration-countdown-${width}.png`), fullPage: true, animations: 'disabled' })
  })
}
